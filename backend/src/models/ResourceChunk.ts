import mongoose, { Schema, Document, Model } from 'mongoose';

/**
 * Chunk of a learning resource used for vector search.
 * Each chunk belongs to a specific resource version and is indexed for fast retrieval.
 */
export interface IResourceChunk extends Document {
  _id: mongoose.Types.ObjectId;
  institutionId: mongoose.Types.ObjectId;
  resourceId: mongoose.Types.ObjectId; // reference to LearningResource
  resourceVersion: number; // version of the parent resource
  chunkIndex: number; // zero‑based order within the resource
  text: string; // extracted slice of the original document
  pageNumber?: number; // optional source page number (when available)
  embedding?: number[]; // vector embedding generated by the provider
  embeddingModel?: string; // model identifier used for embedding generation
  embeddingDimension?: number; // dimensionality of the embedding vector
  createdAt: Date;
  updatedAt: Date;
}

const resourceChunkSchema = new Schema<IResourceChunk>(
  {
    institutionId: { type: Schema.Types.ObjectId, ref: 'Institution', required: true, index: true },
    resourceId: { type: Schema.Types.ObjectId, ref: 'LearningResource', required: true, index: true },
    resourceVersion: { type: Number, required: true, min: 1 },
    chunkIndex: { type: Number, required: true, min: 0 },
    text: { type: String, required: true, trim: true },
    pageNumber: { type: Number },
    embedding: { type: [Number] },
    embeddingModel: { type: String, trim: true },
    embeddingDimension: { type: Number, min: 1 },
  },
  { timestamps: true }
);

// Prevent duplicate chunks for the same resource version and index
resourceChunkSchema.index(
  { resourceId: 1, resourceVersion: 1, chunkIndex: 1 },
  { unique: true }
);

// Helpful tenant‑wide index for retrieval
resourceChunkSchema.index({ institutionId: 1, resourceId: 1, resourceVersion: 1 });

export const ResourceChunk: Model<IResourceChunk> =
  (mongoose.models['ResourceChunk'] as Model<IResourceChunk>) ||
  mongoose.model<IResourceChunk>('ResourceChunk', resourceChunkSchema);

